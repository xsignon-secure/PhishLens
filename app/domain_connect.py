"""Domain Connect (https://www.domainconnect.org): one-click record
publishing without API tokens. The user clicks, signs in at their DNS host
(GoDaddy, IONOS, Cloudflare, WordPress.com, ...), approves, and the host adds
the records from a template PhishLens registered with it.

Flow (synchronous, signed):
1. Discovery: TXT _domainconnect.<domain> names the DNS host's API host;
   https://<it>/v2/<domain>/settings gives providerId, urlSyncUX and urlAPI.
2. Support: GET <urlAPI>/v2/domainTemplates/providers/<ours>/services/<id>.
3. Apply: send the browser to <urlSyncUX>/v2/domainTemplates/providers/
   <ours>/services/<id>/apply?<query>&sig=<RSA-SHA256 of query>&key=<key id>.

Templates (one per record kind) are generated by scripts/domain_connect.py and
must be merged into github.com/Domain-Connect/Templates before DNS hosts will
accept them. See docs/DOMAIN-CONNECT.md.
"""
import base64
import json
import re
import secrets
from urllib.parse import quote, urlencode

import dns.resolver
import httpx

from .config import settings
from .scanner import net

TIMEOUT = 8
# serviceId -> (description, record type, host label, variable, TXT prefix)
SERVICES = {
    "dmarc": ("DMARC policy", "TXT", "_dmarc", "dmarc", "v=DMARC1"),
    "spf": ("SPF record", "TXT", "@", "spf", "v=spf1"),
    "mtasts": ("MTA-STS record", "TXT", "_mta-sts", "mtasts", "v=STSv1"),
    "tlsrpt": ("TLS reporting record", "TXT", "_smtp._tls", "tlsrpt", "v=TLSRPTv1"),
    "bimi": ("BIMI logo record", "TXT", "default._bimi", "bimi", "v=BIMI1"),
    "hosted-dmarc": ("Hosted DMARC", "CNAME", "_dmarc", "target", None),
    "hosted-mtasts": ("Hosted MTA-STS", "CNAME", "_mta-sts", "target", None),
    "mtasts-host": ("MTA-STS policy host", "CNAME", "mta-sts", "target", None),
    "hosted-tlsrpt": ("Hosted TLS reporting", "CNAME", "_smtp._tls", "target", None),
    "hosted-bimi": ("Hosted BIMI", "CNAME", "default._bimi", "target", None),
}
_HOST_RE = re.compile(r"[a-z0-9-]+(\.[a-z0-9-]+)+")


class DomainConnectError(Exception):
    pass


def configured() -> bool:
    return bool(settings.DOMAIN_CONNECT_PROVIDER_ID and settings.DOMAIN_CONNECT_PRIVATE_KEY
                and settings.DOMAIN_CONNECT_KEY_DOMAIN)


# ------------------------------------------------------------------ templates
def template(service_id: str) -> dict:
    """The Domain Connect template JSON for one service."""
    desc, rtype, host, var, prefix = SERVICES[service_id]
    record = {"type": rtype, "host": host, "ttl": 3600}
    if rtype == "TXT":
        record.update({"data": f"%{var}%", "txtConflictMatchingMode": "Prefix",
                       "txtConflictMatchingPrefix": prefix})
    else:
        record["pointsTo"] = f"%{var}%"
    redirect = httpx.URL(settings.APP_URL).host
    return {
        "providerId": settings.DOMAIN_CONNECT_PROVIDER_ID,
        "providerName": settings.DOMAIN_CONNECT_PROVIDER_NAME,
        "serviceId": service_id,
        "serviceName": f"{settings.DOMAIN_CONNECT_PROVIDER_NAME} {desc}",
        "version": 1,
        "description": f"Publishes your {desc} as set up in {settings.DOMAIN_CONNECT_PROVIDER_NAME}.",
        "variableDescription": f"{var}: the full record value",
        "syncBlock": False,
        "syncPubKeyDomain": settings.DOMAIN_CONNECT_KEY_DOMAIN,
        "syncRedirectDomain": redirect,
        "hostRequired": False,
        "records": [record],
    }


def match_service(name: str, rtype: str, value: str, root: str) -> tuple[str, str, dict]:
    """(serviceId, host, variables) for one record under `root`."""
    name = name.lower().rstrip(".")
    if name == root:
        rel = "@"
    elif name.endswith("." + root):
        rel = name[: -len(root) - 1]
    else:
        raise DomainConnectError("The record isn't under this domain")
    for sid, (_, srtype, host, var, prefix) in SERVICES.items():
        if srtype != rtype:
            continue
        if rtype == "TXT" and not value.strip().strip('"').lower().startswith(prefix.lower()):
            continue
        if host == "@":
            sub = "" if rel == "@" else rel
        elif rel == host:
            sub = ""
        elif rel.startswith(host + "."):  # the record lives on a subdomain (Domain Connect "host")
            sub = rel[len(host) + 1:]
        else:
            continue
        value = value.strip().strip('"')
        return sid, sub, {var: value.rstrip(".") if rtype == "CNAME" else value}
    raise DomainConnectError("Domain Connect can't publish this record")


# ------------------------------------------------------------------ discovery
def _get_json(url: str) -> dict | None:
    if not url.startswith("https://"):
        return None
    try:
        status, body = net.safe_fetch_head(url, timeout=TIMEOUT, limit=65536)
    except Exception:
        return None
    if status != 200:
        return None
    try:
        data = json.loads(body)
    except ValueError:
        return None
    return data if isinstance(data, dict) else None


def discover(domain: str, resolver=None) -> dict | None:
    """The DNS host's Domain Connect settings for `domain`, or None. Walks up
    from a subdomain to the zone that publishes _domainconnect."""
    from .scanner.dns_checks import _resolver as default_resolver

    resolver = resolver or default_resolver
    labels = domain.lower().rstrip(".").split(".")
    for i in range(0, max(len(labels) - 1, 1)):
        zone = ".".join(labels[i:])
        try:
            answers = resolver.resolve(f"_domainconnect.{zone}", "TXT", lifetime=TIMEOUT)
        except (dns.resolver.NXDOMAIN, dns.resolver.NoAnswer):
            continue
        except Exception:
            return None
        txt = b"".join(answers[0].strings).decode("ascii", "replace").strip().lower()
        api_host = txt.removeprefix("https://").split("/")[0]
        if not _HOST_RE.fullmatch(api_host):
            return None
        data = _get_json(f"https://{api_host}/v2/{quote(zone)}/settings")
        if not data or not data.get("providerId") or not str(data.get("urlSyncUX", "")).startswith("https://"):
            return None
        return {"zone": zone, "provider_id": str(data["providerId"]),
                "provider_name": str(data.get("providerDisplayName") or data.get("providerName") or data["providerId"])[:60],
                "url_sync_ux": str(data["urlSyncUX"]).rstrip("/"),
                "url_api": str(data.get("urlAPI") or "").rstrip("/")}
    return None


def supports(info: dict, service_id: str) -> bool:
    if not info.get("url_api"):
        return False
    url = (f"{info['url_api']}/v2/domainTemplates/providers/"
           f"{quote(settings.DOMAIN_CONNECT_PROVIDER_ID)}/services/{quote(service_id)}")
    try:
        status, _ = net.safe_fetch_head(url, timeout=TIMEOUT, limit=1024)
    except Exception:
        return False
    return status == 200


# ------------------------------------------------------------------ signed apply URL
def _private_key():
    from cryptography.hazmat.primitives import serialization

    pem = settings.DOMAIN_CONNECT_PRIVATE_KEY.replace("\\n", "\n").encode()
    return serialization.load_pem_private_key(pem, password=None)


def sign(query: str) -> str:
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import padding

    sig = _private_key().sign(query.encode(), padding.PKCS1v15(), hashes.SHA256())
    return base64.b64encode(sig).decode()


def apply_url(info: dict, service_id: str, host: str, variables: dict, state: str | None = None) -> str:
    params = {"domain": info["zone"]}
    if host:
        params["host"] = host
    params.update(variables)
    params["redirect_uri"] = settings.APP_URL.rstrip("/") + "/dashboard?dc=done"
    params["state"] = state or secrets.token_urlsafe(12)
    query = urlencode(params, quote_via=quote)
    signature = sign(query)
    return (f"{info['url_sync_ux']}/v2/domainTemplates/providers/{quote(settings.DOMAIN_CONNECT_PROVIDER_ID)}"
            f"/services/{quote(service_id)}/apply?{query}&sig={quote(signature, safe='')}"
            f"&key={quote(settings.DOMAIN_CONNECT_KEY_ID)}")


def public_key_records(public_pem: bytes) -> list[str]:
    """TXT values to publish at <key id>.<DOMAIN_CONNECT_KEY_DOMAIN>: the
    public key in DER base64, split into numbered parts (p=1, p=2, ...)."""
    from cryptography.hazmat.primitives import serialization

    key = serialization.load_pem_public_key(public_pem)
    der = base64.b64encode(key.public_bytes(serialization.Encoding.DER,
                                            serialization.PublicFormat.SubjectPublicKeyInfo)).decode()
    chunks = [der[i:i + 200] for i in range(0, len(der), 200)]
    return [f"p={n},a=RS256,d={c}" for n, c in enumerate(chunks, 1)]
